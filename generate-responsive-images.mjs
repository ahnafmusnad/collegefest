import sharp from 'sharp';
import { statSync, existsSync, readdirSync, writeFileSync, mkdirSync } from 'fs';
import { join, relative } from 'path';

/* ============================================================
   RESPONSIVE IMAGE VARIANT GENERATOR — AUTO-DISCOVER
   ------------------------------------------------------------
   Scans public/images/ recursively and generates width-based
   variants for EVERY .webp image found. Also generates a
   TypeScript manifest (src/generated/image-variants.ts) that
   ResponsiveImg imports to only request variants that exist.

   Usage: node generate-responsive-images.mjs

   Source files are never deleted.
   ============================================================ */

const IMG_DIR = 'public/images';
const TARGET_WIDTHS = [480, 800, 1200, 1600];
const MANIFEST_TS = 'src/generated/image-variants.ts';

function walk(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir, { withFileTypes: true }).flatMap((e) =>
    e.isDirectory() ? walk(join(dir, e.name)) : [join(dir, e.name)]
  );
}

function webpNameFor(file, width) {
  return file.replace(/\.webp$/i, '') + `.${width}.webp`;
}

async function main() {
  const allImages = walk(IMG_DIR).filter((f) => f.endsWith('.webp'));
  const baseImages = allImages.filter((f) => !/\.\d+\.webp$/.test(f));

  const manifest = {};
  let generated = 0;
  let skipped = 0;

  console.log('=== AUTO-DISCOVERING IMAGES ===');
  console.log(`  Found ${baseImages.length} base images\n`);

  for (const src of baseImages.sort()) {
    const meta = await sharp(src).metadata();
    const origWidth = meta.width || 0;
    const origSize = statSync(src).size;

    const availableWidths = [];

    for (const w of TARGET_WIDTHS) {
      if (w > origWidth) {
        continue;
      }

      const out = webpNameFor(src, w);
      if (existsSync(out)) {
        skipped++;
        availableWidths.push(w);
        continue;
      }

      await sharp(src)
        .resize({ width: w, withoutEnlargement: true })
        .webp({ quality: 82 })
        .toFile(out);

      availableWidths.push(w);
      generated++;
      const rel = src.replace('public/', '');
      const outSize = statSync(out).size;
      console.log(
        `  ${rel} -> ${w}w  (${Math.round(origSize / 1024)}KB -> ${Math.round(outSize / 1024)}KB)`
      );
    }

    const relPath = '/' + relative(IMG_DIR, src).split(join.sep).join('/');
    manifest[relPath] = availableWidths.sort((a, b) => a - b);
  }

  // Write TypeScript manifest module
  mkdirSync(join('src', 'generated'), { recursive: true });
  const tsContent =
    '/* Auto-generated by generate-responsive-images.mjs — do not edit manually */\n' +
    'export const IMAGE_VARIANTS: Record<string, number[]> = ' +
    JSON.stringify(manifest, null, 2) + ';\n';
  writeFileSync(MANIFEST_TS, tsContent);

  console.log(`\n=== RESULT ===\n  generated: ${generated} files\n  skipped  : ${skipped} (already exist)\n  manifest : ${MANIFEST_TS}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
