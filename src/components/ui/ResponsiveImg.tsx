import React from 'react';
import { IMAGE_VARIANTS } from '@/generated/image-variants';

/* ============================================================
   RESPONSIVE IMG — STABLE & BULLETPROOF
   ------------------------------------------------------------
   Reads the IMAGE_VARIANTS manifest (generated by
   generate-responsive-images.mjs) and only includes srcSet
   variants that actually exist. Never 404s on missing variants.

   Usage:
     <ResponsiveImg
       src="/images/hero-castle.webp"
       alt="Castle hero"
       sizes="100vw"
       loading="eager"
       decoding="async"
       fetchPriority="high"
     />

   No `widths` prop needed — the manifest drives everything.
   If a variant is missing, it's simply skipped. The `src`
   always works as fallback.
   ============================================================ */

interface ResponsiveImgProps extends React.ImgHTMLAttributes<HTMLImageElement> {
  src: string;
  sizes?: string;
}

function webpNameFor(src: string, width: number): string {
  return src.replace(/\.webp$/i, '') + `.${width}.webp`;
}

export const ResponsiveImg: React.FC<ResponsiveImgProps> = ({
  src,
  alt = '',
  sizes,
  className = '',
  loading = 'lazy',
  decoding = 'async',
  ...rest
}) => {
  const availableWidths = IMAGE_VARIANTS[src] ?? [];

  const srcSet = availableWidths
    .filter((w) => w > 0)
    .map((w) => `${webpNameFor(src, w)} ${w}w`)
    .join(', ');

  return (
    <img
      src={src}
      srcSet={srcSet || undefined}
      sizes={sizes}
      alt={alt}
      loading={loading}
      decoding={decoding}
      className={className}
      {...rest}
    />
  );
};

export default ResponsiveImg;
